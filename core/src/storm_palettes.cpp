int get_dmg_palette_count() {
    return static_cast<int>(sizeof(kDmgPalettes) / sizeof(kDmgPalettes[0]));
}

const char* get_dmg_palette_name(int index) {
    int n = get_dmg_palette_count();
    if (index < 0 || index >= n) return nullptr;
    return kDmgPalettes[index].name;
}

const DmgPaletteEntry* get_dmg_palette(int index) {
    int n = get_dmg_palette_count();
    if (index < 0 || index >= n) index = 0;
    return &kDmgPalettes[index];
}

void get_effective_dmg_palette(int index, const uint32_t custom[4],
                               uint32_t out_bg[4], uint32_t out_obj0[4], uint32_t out_obj1[4]) {
    if (index < 0 && custom) {
        for (int i = 0; i < 4; ++i) {
            uint32_t c = custom[i] & 0x00FFFFFFu;
            out_bg[i] = c;
            out_obj0[i] = c;
            out_obj1[i] = c;
        }
        return;
    }
    const DmgPaletteEntry* p = get_dmg_palette(index);
    for (int i = 0; i < 4; ++i) {
        out_bg[i] = p->bg[i];
        out_obj0[i] = p->obj0[i];
        out_obj1[i] = p->obj1[i];
    }
}

